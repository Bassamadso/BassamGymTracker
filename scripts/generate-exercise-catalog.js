/* eslint-env node */
/**
 * Builds src/exerciseCatalog.ts from the open free-exercise-db dataset
 * (https://github.com/yuhonas/free-exercise-db, Unlicense / public domain).
 *
 *   npm run catalog                 # download the latest dataset
 *   npm run catalog -- ./local.json # or use a local copy
 */
const fs = require('fs');
const path = require('path');

const SOURCE_URL =
  'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/dist/exercises.json';
const OUT = path.join(__dirname, '..', 'src', 'exerciseCatalog.ts');

// The dataset names 17 fine-grained muscles; the app groups them into 7.
const MUSCLE_TO_GROUP = {
  chest: 'Chest',
  lats: 'Back',
  'middle back': 'Back',
  'lower back': 'Back',
  traps: 'Back',
  quadriceps: 'Legs',
  hamstrings: 'Legs',
  glutes: 'Legs',
  calves: 'Legs',
  adductors: 'Legs',
  abductors: 'Legs',
  shoulders: 'Shoulders',
  biceps: 'Arms',
  triceps: 'Arms',
  forearms: 'Arms',
  abdominals: 'Core',
  neck: 'Other',
};

// Not lifts you log as weight × reps, so keep them out of the muscle groups.
const OTHER_CATEGORIES = new Set(['cardio', 'stretching']);

function toEntry(raw) {
  const name = String(raw.name ?? '').trim();
  const id = String(raw.id ?? '').trim();
  if (!name || !id)
    throw new Error(`Entry without name/id: ${JSON.stringify(raw)}`);

  let muscle = 'Other';
  if (!OTHER_CATEGORIES.has(raw.category)) {
    const primary = (raw.primaryMuscles || [])[0];
    muscle = MUSCLE_TO_GROUP[primary];
    // Fail loudly if the dataset grows a muscle we have not mapped
    if (!muscle) throw new Error(`Unmapped muscle "${primary}" on "${name}"`);
  }
  return [`db-${id}`, name, muscle];
}

async function load() {
  const file = process.argv[2];
  if (file) return JSON.parse(fs.readFileSync(file, 'utf8'));
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`Download failed: ${res.status}`);
  return res.json();
}

load()
  .then(data => {
    if (!Array.isArray(data) || data.length === 0) {
      throw new Error('Dataset is empty or not an array');
    }
    const entries = data
      .map(toEntry)
      .sort((a, b) => a[1].localeCompare(b[1]) || a[0].localeCompare(b[0]));
    const ids = new Set(entries.map(e => e[0]));
    if (ids.size !== entries.length)
      throw new Error('Duplicate ids in dataset');

    const body = entries.map(e => `  ${JSON.stringify(e)},`).join('\n');
    fs.writeFileSync(
      OUT,
      `// Generated by scripts/generate-exercise-catalog.js — do not edit by hand.
// Source: free-exercise-db (https://github.com/yuhonas/free-exercise-db), public domain.
import { MuscleGroup } from './types';

/** [id, name, muscle] */
export const EXERCISE_CATALOG: [string, string, MuscleGroup][] = [
${body}
];
`,
    );
    console.log(
      `Wrote ${entries.length} exercises to ${path.relative(
        process.cwd(),
        OUT,
      )}`,
    );
  })
  .catch(err => {
    console.error(err.message);
    process.exit(1);
  });
